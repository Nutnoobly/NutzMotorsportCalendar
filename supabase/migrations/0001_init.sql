-- INDEXES
CREATE INDEX IF NOT EXISTS idx_events_starts_at ON EVENTS(event_starts_at);
CREATE INDEX IF NOT EXISTS idx_events_series_season ON EVENTS(serie_id, event_season);
CREATE INDEX IF NOT EXISTS idx_sessions_event_starts ON SESSIONS(event_id, session_starts_at);
CREATE INDEX IF NOT EXISTS idx_results_event_session ON RESULTS(event_id, session_type);
CREATE INDEX IF NOT EXISTS idx_events_external_id ON EVENTS(serie_id, event_external_id) WHERE event_external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_drivers_external_id ON DRIVERS(serie_id, driver_external_id) WHERE driver_external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_teams_external_id ON TEAMS(serie_id, team_external_id) WHERE team_external_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_circuits_slug ON CIRCUITS(circuit_slug);

